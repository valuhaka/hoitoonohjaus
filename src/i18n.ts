export const DICTS: Record<Lang, Dict> = { fi, sv, en }

export const formatDate = (iso: string, lang: Lang) =>
  new Date(iso).toLocaleDateString(LOCALES[lang])

export const formatFee = (fee: number | null, lang: Lang) =>
  fee === null
    ? DICTS[lang].feeUnknown
    : fee === 0
    ? DICTS[lang].free
    : `${new Intl.NumberFormat(LOCALES[lang], { style: 'currency', currency: 'EUR' }).format(fee)} / ${DICTS[lang].perSession}`

// Times are stored as 'HH:MM'; Finnish and Swedish write them as HH.MM
export const formatTime = (time: string, lang: Lang) => (lang === 'en' ? time : time.replace(':', '.'))

export const I18n = createContext<{ t: Dict; lang: Lang }>({ t: fi, lang: 'fi' })
export const useT = () => useContext(I18n)
