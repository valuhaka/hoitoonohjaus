export type Lang = 'fi' | 'sv' | 'en' | 'ru'
export type TreatmentKind =
  | 'group'        // professionally led group treatment
  | 'peerGroup'    // peer support group, often with a trained facilitator
  | 'individual'   // one-to-one appointments
  | 'dropIn'       // walk-in or low-threshold conversation help
  | 'helpline'
  | 'chat'
  | 'online'       // therapist-supported online therapy
  | 'selfCare'     // self-guided programme or app
  | 'organisation' // association that runs several activities; see its site
  | 'specialist'   // specialist or medical care, usually by referral
export type SessionType =
  | 'inPerson'
  | 'hybrid' // both on site and remotely
  | 'video'  // live remote meetings
  | 'phone'
  | 'chat'   // written conversation
  | 'online' // web programme, app or nettiterapia
