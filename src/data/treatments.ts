export const GENDERS: Gender[] = ['male', 'female', 'other']
export type EnrolmentStatus =
  | 'dropIn'             // come without registering
  | 'continuous'         // contact any time, no fixed intake
  | 'applyNow'           // registration or application open
  | 'applyLater'         // next group announced, application not open yet
  | 'registrationClosed' // deadline passed, group not started yet
  | 'inProgress'         // group already running
  | 'full'               // the page says the group is full
  | 'referral'           // access by referral only
  | 'unknown'
