// REAL treatment and support options compiled from 23 public source pages (see SOURCE_URLS).
// Unlike GROUPS this data is not synthetic, so unknown values stay null instead of being invented:
// - No source publishes live vacancy numbers. `vacancy.status` records what the page says
//   ("Ryhmä on täynnä", registration deadline passed, drop-in, ...) as of RETRIEVED_AT.
// - Coordinates come from the Helsinki region service registry (palvelukartta) for public units,
//   otherwise from OpenStreetMap Nominatim.
// - Image URLs were checked to resolve; `kind` says whether a picture shows the building or is a logo/illustration.
//
// Tagging rules (matching depends on these, keep them strict):
// 1. Tag a problem only when the source names it, or when it follows directly from the target group
//    (divorce group -> ero, bereavement group -> suru, AA -> paihteet).
// 2. Services for the relatives of someone with a substance problem also get paihteet,
//    since the patient's own notes will mention the relative's drinking or drug use.
// 3. nuoret = young adults: tag it when the age range reaches into 18–29.
//    ikaantyneet: tag it when the service is aimed at people 65+.
// 4. General low-threshold conversation help gets only the problems the page lists, never disorder-specific tags.
// 5. If no hashtag fits (psychosis, eating disorders, gambling, autism, specialist care by referral),
//    leave tags empty and give `untaggedReason`, so the entry is listed but never auto-matched.
// 6. genders lists who the service is for. Restrict it only when the target group names a gender
//    (men's groups, fathers, women and girls, mothers); a service that also takes relatives is open to all.
// 7. format is the session type: video for live remote meetings (Teams, Zoom), chat for written
//    conversation (chat, writing-based groups, peer-support apps), online for web programmes and nettiterapia.
